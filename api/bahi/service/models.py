"""What goes over the wire, as Pydantic models.

These are the API contract. FastAPI turns them into the OpenAPI spec, and the
frontend's TypeScript types are generated from that spec (`make openapi`), so a
field renamed here breaks the frontend's type check rather than its screens.

Pydantic lives here and nowhere else. The domain uses frozen dataclasses, so the
purity test needs no exceptions.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, Field

from bahi.domain.book import Chip, Joined

EntryStatus = Literal["recorded", "confirmed", "disputed", "corrected", "settled"]


class ShopOut(BaseModel):
    id: str
    name: str
    locality: str


class RhythmOut(BaseModel):
    n: int
    median_gap: int | None
    max_gap: int | None
    last_paid: date | None


class LineOut(BaseModel):
    customer_id: str
    display_name: str
    tag: str | None
    joined: Joined
    balance_paise: int
    day: int
    chip: Chip
    rhythm: RhythmOut


class BookOut(BaseModel):
    customer_count: int
    invited_count: int
    owing_count: int
    outstanding_paise: int
    lines: list[LineOut]


class ShopBookOut(BaseModel):
    """The shopkeeper's book. Also written to contract/shop.json by `make db`."""

    synthetic: Literal[True] = True
    about: str = "Synthetic demo data for one seeded shop."
    today: date
    shop: ShopOut
    book: BookOut


class CustomerOut(BaseModel):
    id: str
    display_name: str
    tag: str | None
    joined: Joined


class WaitingOut(BaseModel):
    scan_id: str
    customer_id: str
    display_name: str
    tag: str | None
    scanned_at: datetime
    #: Seconds since he scanned, by the server's clock. The browser's clock may
    #: disagree with the product's (the demo pins the date), so it never does this sum.
    waited_s: int
    first_time: bool


class CounterOut(BaseModel):
    """Everyone at the counter, oldest scan first."""

    shop_id: str
    waiting: list[WaitingOut]


class EntryOut(BaseModel):
    id: str
    customer_id: str
    display_name: str
    shop_id: str
    shop_name: str
    amount_paise: int
    paid_paise: int
    status: EntryStatus
    recorded_at: datetime
    note: str | None
    spoken_text: str | None
    corrects_entry_id: str | None
    acknowledged_at: datetime | None
    #: The confirm button's words, generated by the server so that what he taps
    #: and what is stored are the same string.
    button: str


class RecordIn(BaseModel):
    """An udhaar entry. Either a scan (he is at the counter) or a customer."""

    amount_paise: int = Field(gt=0)
    scan_id: UUID | None = None
    customer_id: UUID | None = None
    note: str | None = Field(default=None, max_length=80)
    spoken_text: str | None = Field(default=None, max_length=200)


class JoinIn(BaseModel):
    """He scanned the udhaar QR. A first-timer tells us the name to use."""

    person_id: UUID
    name: str | None = Field(default=None, min_length=1, max_length=40)


class JoinOut(BaseModel):
    customer_id: str
    scan_id: str
    shop: ShopOut
    first_time: bool


class ScanOut(BaseModel):
    scan_id: str
    state: Literal["waiting", "recorded", "left", "expired"]
    entry: EntryOut | None


class PersonIn(BaseModel):
    person_id: UUID


class DisputeIn(BaseModel):
    person_id: UUID
    reason: str | None = Field(default=None, max_length=280)
